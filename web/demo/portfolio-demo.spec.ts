import { expect, test } from '@playwright/test'
import path from 'node:path'

const pause = (page: import('@playwright/test').Page, ms: number) => page.waitForTimeout(ms)

test('青柠 Agent 两分钟完整演示', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('用户名', { exact: true })).toBeVisible()
  await pause(page, 3500)
  await page.getByLabel('用户名', { exact: true }).fill('demo-user')
  await page.getByLabel('密码', { exact: true }).fill('qingning-demo')
  await pause(page, 2500)
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  await expect(page.getByText('今天想聊什么，或者想先处理哪件事？')).toBeVisible()
  await pause(page, 8000)

  const composer = page.locator('.composer textarea')
  await composer.fill('明天下午 3 点提醒我体检')
  await pause(page, 2500)
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('heading', { name: '提醒面板' })).toBeVisible()
  await expect(page.locator('.reminder-card').filter({ hasText: '体检' })).toBeVisible()
  await pause(page, 13_000)

  await page.getByRole('button', { name: '工作台', exact: true }).click()
  await composer.fill('在日历创建明天下午 3 点的项目评审日程')
  await pause(page, 2500)
  await page.getByRole('button', { name: '发送', exact: true }).click()
  const confirmation = page.locator('.agent-plan').last()
  await expect(confirmation).toContainText('待确认', { timeout: 30_000 })
  await pause(page, 14_000)
  await confirmation.getByRole('button', { name: '拒绝', exact: true }).click()
  await expect(confirmation).toContainText('已拒绝')
  await pause(page, 6000)

  const fileInput = page.locator('input[type="file"]')
  await fileInput.setInputFiles(path.resolve('demo/fixtures/redacted-rental.png'))
  await expect(page.locator('.upload-preview')).toBeVisible()
  await pause(page, 11_500)
  await composer.fill('请提取这份脱敏合同的金额、日期和风险点')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.agent-plan').last()).toContainText('提取文档', { timeout: 30_000 })
  await pause(page, 14_000)

  const profile = page.getByRole('button', { name: /demo-user/ })
  await profile.click()
  await page.getByRole('menuitem', { name: '能力管理' }).click()
  await page.getByRole('button', { name: '文档提取', exact: true }).click()
  await expect(page.getByText('脱敏房屋租赁合同')).toBeVisible()
  await page.getByText('脱敏房屋租赁合同').click()
  await expect(page.getByRole('heading', { name: '脱敏房屋租赁合同' })).toBeVisible()
  await pause(page, 14_000)
  await page.getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.getByRole('button', { name: '关闭', exact: true }).first().click()

  const documentText = '脱敏房屋租赁合同。月租6500元，押金13000元。租期自2026年11月1日至2027年10月31日。租赁期满且承租方无违约、房屋无损坏的，出租方应于7个工作日内无息退还押金。承租方提前退租应提前30日书面通知，并支付一个月租金作为违约金。房屋主体结构自然损坏由出租方维修，使用不当造成的损坏由承租方承担。双方姓名、电话、证件号和详细地址均已脱敏。除原文明确列出的金额、日期、期限和责任外，不应推断其他未写明事项。请告诉我押金何时退还，并标注引用。'
  await composer.fill(documentText)
  await pause(page, 3500)
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText(/已引用原文/)).toBeVisible({ timeout: 30_000 })
  const plan = page.locator('.agent-plan').last()
  await plan.locator('summary').click()
  await expect(plan).toBeVisible()
  await pause(page, 19_000)
})
